"""
Локальная (без обращения к каким-либо API) транслитерация грузинского
чат-транслита (латиницы) в грузинский алфавит (мхедрули).

Это детерминированный best-effort конвертер, а не лингвистический анализатор:
грузинский язык не сводится 1:1 к латинице — например, сочетание "ts" может
означать и წ, и ც, а "ch" — и ჭ, и ჩ (то же для k/q, t/T, p/f — придыхательные
vs абруптивные согласные, которые в бытовом транслите обычно не различают).
Для каждой такой пары ниже зафиксирован один "дефолтный" вариант — для
однозначных бытовых фраз это работает хорошо, а для текста, где неоднозначность
критична, её призвана распутывать по контексту уже Gemini (см. smart_routing.py
и SYSTEM_PROMPT_GEO_TO_RU_COMPLEX в prompts.py — именно поэтому "сложный" текст
осознанно не отправляется напрямую в Google Translate).

⚡ Оптимизирована для скорости: использует str.translate() для букв и 
специальную обработку диграфов.
"""

# Сначала сложные буквосочетания (проверяются first, по длине от 2 символов к 1) —
# порядок важен: без этого "zh" распалось бы на z+h ещё до того, как мы успели
# бы распознать диграф целиком.
_DIGRAPHS = {
    "dz": "ძ",
    "ts": "ც",  # альтернатива: წ (абруптивный) — неоднозначность, см. докстринг модуля
    "ch": "ჩ",  # альтернатива: ჭ (абруптивный)
    "sh": "შ",
    "gh": "ღ",
    "kh": "ხ",
    "zh": "ჟ",
}

_SINGLE_LETTERS = {
    "a": "ა",
    "b": "ბ",
    "g": "გ",
    "d": "დ",
    "e": "ე",
    "v": "ვ",
    "z": "ზ",
    "t": "თ",  # альтернатива: ტ (абруптивный)
    "i": "ი",
    "k": "კ",  # альтернатива: ქ (придыхательный)
    "l": "ლ",
    "m": "მ",
    "n": "ნ",
    "o": "ო",
    "p": "პ",  # альтернатива: ფ (придыхательный)
    "r": "რ",
    "s": "ს",
    "u": "უ",
    "f": "ფ",
    "q": "ყ",
    "y": "ი",  # грубое приближение — в стандартном транслите не используется
    "h": "ჰ",
    "j": "ჯ",
    "x": "ხ",  # распространённая альтернатива для "kh" (например, "xar" = "khar")
    "c": "ც",  # одиночная "c" часто используется вместо диграфа "ts" (например, "gacnobebt")
    "w": "წ",  # распространённая альтернатива для абруптивного "ts'"
}

_MAX_DIGRAPH_LEN = 2

# ⚡ Таблица для быстрого преобразования через str.translate()
_TRANSLATION_TABLE = str.maketrans(_SINGLE_LETTERS)


def transliterate_to_mkhedruli(text: str) -> str:
    """
    Конвертирует грузинский чат-транслит (латиницу) в мхедрули жадным 
    сканированием: на каждой позиции сперва пробуем самое длинное
    известное буквосочетание (диграф), затем одну букву.
    
    ⚡ Оптимизировано:
    - str.translate() для однобуквенных замен (намного быстрее, чем посимвольный цикл)
    - Быстрая обработка диграфов без пересчётов
    """
    if not text:
        return text
    
    result = []
    lowered = text.lower()
    i = 0
    n = len(text)
    
    while i < n:
        # Проверяем диграфы (2 символа)
        if i + _MAX_DIGRAPH_LEN <= n:
            candidate = lowered[i : i + _MAX_DIGRAPH_LEN]
            if candidate in _DIGRAPHS:
                result.append(_DIGRAPHS[candidate])
                i += _MAX_DIGRAPH_LEN
                continue
        
        # Проверяем однобуквенные замены
        char = lowered[i]
        if char in _SINGLE_LETTERS:
            result.append(_SINGLE_LETTERS[char])
        else:
            # Оставляем как есть: цифры, кириллица, пунктуация и т.п.
            result.append(text[i])
        i += 1
    
    return "".join(result)